ALTER TABLE vendors ADD COLUMN IF NOT EXISTS stripe_payouts_enabled boolean NOT NULL DEFAULT false;
ALTER TABLE vendors ADD COLUMN IF NOT EXISTS stripe_details_submitted boolean NOT NULL DEFAULT false;
