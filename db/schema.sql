-- Neighborhood Perks booking schema. Idempotent: safe to run on every deploy.
-- All instants are timestamptz (UTC on disk). Weekly hours are local wall-clock
-- times in the vendor's timezone, so DST is handled when slots are generated.

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE IF NOT EXISTS vendors (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name            text NOT NULL,
  business_name   text,
  email           text NOT NULL,
  phone           text,
  timezone        text NOT NULL DEFAULT 'America/Los_Angeles',
  min_notice_min  integer NOT NULL DEFAULT 720 CHECK (min_notice_min >= 0),
  max_days_ahead  integer NOT NULL DEFAULT 60 CHECK (max_days_ahead BETWEEN 1 AND 365),
  slot_step_min   integer NOT NULL DEFAULT 30 CHECK (slot_step_min IN (15, 30, 60)),
  ics_token       text NOT NULL,  -- random, generated by the app (lib/crypto.mjs)
  active          boolean NOT NULL DEFAULT true,
  created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS vendors_email_key ON vendors (lower(email));
CREATE UNIQUE INDEX IF NOT EXISTS vendors_ics_key ON vendors (ics_token);

CREATE TABLE IF NOT EXISTS users (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  email          text NOT NULL,
  password_hash  text,
  role           text NOT NULL CHECK (role IN ('admin', 'vendor')),
  vendor_id      uuid REFERENCES vendors(id) ON DELETE CASCADE,
  created_at     timestamptz NOT NULL DEFAULT now(),
  CHECK ((role = 'vendor') = (vendor_id IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS users_email_key ON users (lower(email));

CREATE TABLE IF NOT EXISTS sessions (
  token_hash  text PRIMARY KEY,
  user_id     uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at  timestamptz NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS invites (
  token_hash  text PRIMARY KEY,
  user_id     uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at  timestamptz NOT NULL,
  used_at     timestamptz
);

CREATE TABLE IF NOT EXISTS services (
  id      uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  slug    text NOT NULL UNIQUE,
  name    text NOT NULL,
  active  boolean NOT NULL DEFAULT true,
  sort    integer NOT NULL DEFAULT 0
);

-- What each vendor offers, and how long it takes them
CREATE TABLE IF NOT EXISTS vendor_services (
  vendor_id     uuid NOT NULL REFERENCES vendors(id) ON DELETE CASCADE,
  service_id    uuid NOT NULL REFERENCES services(id) ON DELETE CASCADE,
  duration_min  integer NOT NULL CHECK (duration_min BETWEEN 15 AND 720),
  buffer_min    integer NOT NULL DEFAULT 15 CHECK (buffer_min BETWEEN 0 AND 240),
  price_cents   integer CHECK (price_cents >= 0),
  active        boolean NOT NULL DEFAULT true,
  PRIMARY KEY (vendor_id, service_id)
);

-- Weekly working hours. weekday: 1 = Monday … 7 = Sunday (ISO, matches Luxon)
CREATE TABLE IF NOT EXISTS availability_rules (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  vendor_id   uuid NOT NULL REFERENCES vendors(id) ON DELETE CASCADE,
  weekday     smallint NOT NULL CHECK (weekday BETWEEN 1 AND 7),
  start_time  time NOT NULL,
  end_time    time NOT NULL,
  CHECK (end_time > start_time)
);
CREATE INDEX IF NOT EXISTS availability_rules_vendor ON availability_rules (vendor_id);

-- Blocked time: vacations, appointments elsewhere, a day off
CREATE TABLE IF NOT EXISTS time_off (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  vendor_id  uuid NOT NULL REFERENCES vendors(id) ON DELETE CASCADE,
  starts_at  timestamptz NOT NULL,
  ends_at    timestamptz NOT NULL,
  note       text,
  CHECK (ends_at > starts_at)
);
CREATE INDEX IF NOT EXISTS time_off_vendor ON time_off USING gist (vendor_id, tstzrange(starts_at, ends_at));

CREATE TABLE IF NOT EXISTS bookings (
  id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  vendor_id          uuid NOT NULL REFERENCES vendors(id),
  service_id         uuid NOT NULL REFERENCES services(id),
  starts_at          timestamptz NOT NULL,
  ends_at            timestamptz NOT NULL,
  -- end of the job plus the vendor's travel/cleanup buffer; this is what blocks the calendar
  blocked_until      timestamptz NOT NULL,
  status             text NOT NULL DEFAULT 'confirmed'
                       CHECK (status IN ('confirmed', 'completed', 'cancelled', 'no_show')),
  customer_name      text NOT NULL,
  customer_phone     text NOT NULL,
  customer_email     text NOT NULL,
  address            text NOT NULL,
  neighborhood       text,
  notes              text,
  price_cents        integer,
  manage_token_hash  text NOT NULL,
  cancelled_by       text,
  cancel_reason      text,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  CHECK (ends_at > starts_at AND blocked_until >= ends_at)
);
CREATE UNIQUE INDEX IF NOT EXISTS bookings_manage_key ON bookings (manage_token_hash);
CREATE INDEX IF NOT EXISTS bookings_vendor_time ON bookings (vendor_id, starts_at);

-- The guarantee: a vendor can never hold two live bookings that overlap,
-- no matter how many requests race. Enforced by Postgres itself.
DO $$ BEGIN
  ALTER TABLE bookings ADD CONSTRAINT bookings_no_overlap
    EXCLUDE USING gist (vendor_id WITH =, tstzrange(starts_at, blocked_until) WITH &&)
    WHERE (status IN ('confirmed', 'completed'));
EXCEPTION WHEN duplicate_object OR duplicate_table THEN NULL;
END $$;

-- Every change to a booking, who made it and when
CREATE TABLE IF NOT EXISTS booking_events (
  id          bigserial PRIMARY KEY,
  booking_id  uuid NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  type        text NOT NULL,
  actor       text NOT NULL,
  data        jsonb,
  at          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS booking_events_booking ON booking_events (booking_id);

-- Simple fixed-window rate limiting for public endpoints
CREATE TABLE IF NOT EXISTS rate_limits (
  key         text PRIMARY KEY,
  count       integer NOT NULL,
  window_end  timestamptz NOT NULL
);

-- Where providers work. Customers pick an area (or type a ZIP) and see who serves it.
CREATE TABLE IF NOT EXISTS areas (
  id      uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  slug    text NOT NULL UNIQUE,
  name    text NOT NULL,
  zips    text[] NOT NULL DEFAULT '{}',
  active  boolean NOT NULL DEFAULT true,
  sort    integer NOT NULL DEFAULT 100
);

CREATE TABLE IF NOT EXISTS vendor_areas (
  vendor_id  uuid NOT NULL REFERENCES vendors(id) ON DELETE CASCADE,
  area_id    uuid NOT NULL REFERENCES areas(id) ON DELETE CASCADE,
  PRIMARY KEY (vendor_id, area_id)
);
CREATE INDEX IF NOT EXISTS vendor_areas_area ON vendor_areas (area_id);

